import AppKit
import Combine
import CryptoKit
import ImageIO

final class ClipboardManager: ObservableObject {
    static let shared = ClipboardManager()

    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var isMonitoring = true

    private let settings = AppSettings.shared
    private var lastChangeCount: Int
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?
    private var bag = Set<AnyCancellable>()

    private static let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, NSPasteboard.PasteboardType("public.jpeg")]

    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType"
    ]

    private init() {
        lastChangeCount = NSPasteboard.general.changeCount

        if settings.saveHistory {
            items = ClipboardStore.loadHistory()
            let keep = Set(items.compactMap { $0.imageFile })
            Task.detached(priority: .background) {
                ClipboardStore.sweepOrphans(keeping: keep)
            }
        } else {
            ClipboardStore.wipe()
        }

        startMonitoring()

        settings.$maxItems
            .dropFirst()
            .sink { [weak self] limit in self?.enforceLimit(limit) }
            .store(in: &bag)

        settings.$saveHistory
            .dropFirst()
            .sink { [weak self] enabled in
                if enabled {
                    self?.scheduleSave()
                } else {
                    ClipboardStore.deleteHistoryFile()
                }
            }
            .store(in: &bag)
    }

    func startMonitoring() {
        guard timer == nil else { return }
        isMonitoring = true
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.checkPasteboard() }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stopMonitoring() {
        isMonitoring = false
        timer?.invalidate()
        timer = nil
    }

    func flush() {
        saveWork?.cancel()
        guard settings.saveHistory else { return }
        ClipboardStore.saveHistory(items)
    }

    private func checkPasteboard() {
        let pb = NSPasteboard.general
        let change = pb.changeCount
        guard change != lastChangeCount else { return }
        lastChangeCount = change

        let types = pb.types ?? []
        let front = NSWorkspace.shared.frontmostApplication
        let app = front?.localizedName
        let bundle = front?.bundleIdentifier

        if settings.ignoreConcealed, types.contains(where: { Self.concealedTypes.contains($0.rawValue) }) { return }
        if let bundle, settings.ignoredApps.contains(bundle) { return }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let item = ClipboardItem.makeFiles(urls, app: app, bundleID: bundle)
            insert(item) { $0.fileURLs == urls }
            return
        }

        let hasString = types.contains(.string)
        let hasRichText = types.contains(.rtf) || types.contains(.rtfd)

        if !(hasString && hasRichText), let imageType = Self.imageTypes.first(where: { types.contains($0) }), let data = pb.data(forType: imageType) {
            captureImage(data: data, type: imageType, app: app, bundleID: bundle)
            return
        }

        guard let string = pb.string(forType: .string), string.utf8.count <= 5_000_000, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        let item = ClipboardItem.makeText(string, app: app, bundleID: bundle)
        insert(item) { $0.text == string && $0.imageHash == nil && $0.fileURLs == nil }
    }

    private func captureImage(data: Data, type: NSPasteboard.PasteboardType, app: String?, bundleID: String?) {
        let limit = settings.maxImageMB * 1_048_576
        guard data.count <= limit else { return }

        let fileExtension = type == .png ? "png" : (type == .tiff ? "tiff" : "jpg")
        let typeRaw = type.rawValue

        Task.detached(priority: .utility) { [weak self] in
            let digest = SHA256.hash(data: data)
            let hash = digest.map { String(format: "%02x", $0) }.joined()

            var width = 0
            var height = 0
            if let source = CGImageSourceCreateWithData(data as CFData, nil),
               let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any] {
                width = props[kCGImagePropertyPixelWidth] as? Int ?? 0
                height = props[kCGImagePropertyPixelHeight] as? Int ?? 0
            }
            guard width > 0, height > 0 else { return }

            let isDuplicate = await MainActor.run { self?.bumpExistingImage(hash: hash) ?? true }
            if isDuplicate { return }

            let name = "\(UUID().uuidString).\(fileExtension)"
            guard ClipboardStore.writeImage(data, name: name) else { return }

            await MainActor.run {
                guard let self else { return }
                var item = ClipboardItem(type: .image, date: Date(), sourceApp: app, sourceBundleID: bundleID)
                item.imageFile = name
                item.imageType = typeRaw
                item.imageHash = hash
                item.pixelWidth = width
                item.pixelHeight = height
                item.byteCount = data.count
                self.insert(item) { _ in false }
            }
        }
    }

    private func bumpExistingImage(hash: String) -> Bool {
        guard let idx = items.firstIndex(where: { $0.imageHash == hash }) else { return false }
        items[idx].date = Date()
        normalizeOrder()
        scheduleSave()
        return true
    }

    private func insert(_ item: ClipboardItem, matching isDuplicate: (ClipboardItem) -> Bool) {
        if let idx = items.firstIndex(where: isDuplicate) {
            items[idx].date = Date()
            items[idx].sourceApp = item.sourceApp
            items[idx].sourceBundleID = item.sourceBundleID
        } else {
            items.append(item)
        }
        normalizeOrder()
        enforceLimit(settings.maxItems)
        if settings.playSounds { NSSound(named: "Tink")?.play() }
        scheduleSave()
    }

    private func normalizeOrder() {
        items.sort { a, b in
            a.isPinned != b.isPinned ? a.isPinned : a.date > b.date
        }
    }

    private func enforceLimit(_ limit: Int) {
        var removed: [ClipboardItem] = []
        while items.filter({ !$0.isPinned }).count > limit, let idx = items.lastIndex(where: { !$0.isPinned }) {
            removed.append(items.remove(at: idx))
        }
        guard !removed.isEmpty else { return }
        discardFiles(of: removed)
        scheduleSave()
    }

    private func discardFiles(of removed: [ClipboardItem]) {
        let names = removed.compactMap { $0.imageFile }
        guard !names.isEmpty else { return }
        Task.detached(priority: .background) {
            ClipboardStore.deleteImages(named: names)
        }
    }

    private func scheduleSave() {
        guard settings.saveHistory else { return }
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            guard let self else { return }
            let snapshot = self.items
            Task.detached(priority: .utility) {
                ClipboardStore.saveHistory(snapshot)
            }
        }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.8, execute: work)
    }

    func togglePin(_ item: ClipboardItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].isPinned.toggle()
        normalizeOrder()
        enforceLimit(settings.maxItems)
        scheduleSave()
    }

    func delete(_ item: ClipboardItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        let removed = items.remove(at: idx)
        discardFiles(of: [removed])
        scheduleSave()
    }

    func clearAll(keepPinned: Bool) {
        let removed = items.filter { !keepPinned || !$0.isPinned }
        items.removeAll { !keepPinned || !$0.isPinned }
        discardFiles(of: removed)
        scheduleSave()
    }

    func paste(_ item: ClipboardItem) {
        writeToPasteboard(item)

        let controller = ClipboardPanelController.shared
        let target = controller.previousApp
        controller.close()

        if settings.autoPaste {
            PasteHelper.paste(into: target)
        } else {
            PasteHelper.restoreFocus(to: target)
        }
    }

    func copy(_ item: ClipboardItem) {
        writeToPasteboard(item)
    }

    private func writeToPasteboard(_ item: ClipboardItem) {
        let pb = NSPasteboard.general
        pb.clearContents()

        switch item.type {
        case .file:
            if let urls = item.fileURLs {
                pb.writeObjects(urls as [NSURL])
            }
        case .image:
            if let name = item.imageFile, let data = ClipboardStore.readImage(name: name) {
                pb.setData(data, forType: NSPasteboard.PasteboardType(item.imageType ?? NSPasteboard.PasteboardType.png.rawValue))
            }
        default:
            if let text = item.text {
                pb.setString(text, forType: .string)
            }
        }

        lastChangeCount = pb.changeCount
    }
}
